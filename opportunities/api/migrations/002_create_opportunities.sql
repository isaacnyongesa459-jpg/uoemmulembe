CREATE TABLE IF NOT EXISTS opportunities (
  id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  source_id VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  source_url_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  title VARCHAR(500) NOT NULL,
  organization VARCHAR(255) NULL,
  category ENUM(
    'jobs',
    'scholarships',
    'fellowships',
    'grants_funding',
    'volunteering',
    'technology',
    'courses_training',
    'entrepreneurship_startups',
    'conferences_programs',
    'other'
  ) NOT NULL DEFAULT 'other',
  description TEXT NULL,
  eligibility TEXT NULL,
  location VARCHAR(255) NULL,
  application_link VARCHAR(2048) NULL,
  application_link_candidates JSON NULL,
  source_name VARCHAR(200) NOT NULL,
  source_link VARCHAR(2048) NOT NULL,
  deadline DATE NULL,
  deadline_text VARCHAR(160) NULL,
  publication_date DATETIME NULL,
  discovered_at DATETIME NOT NULL,
  last_updated_at DATETIME NOT NULL,
  status ENUM('pending_verification', 'active', 'expired', 'archived') NOT NULL DEFAULT 'pending_verification',
  work_mode ENUM('remote', 'onsite', 'hybrid', 'unknown') NOT NULL DEFAULT 'unknown',
  funding_details TEXT NULL,
  verification_flags JSON NOT NULL,
  source_category_slugs JSON NULL,
  is_suspicious TINYINT(1) NOT NULL DEFAULT 0,
  verified_at DATETIME NULL,
  verified_by VARCHAR(255) NULL,
  reviewed_at DATETIME NULL,
  review_notes TEXT NULL,
  expired_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_opportunities_source_url_hash (source_id, source_url_hash),
  KEY idx_opportunities_public_gate (status, verified_at, deadline),
  KEY idx_opportunities_category (category, status, verified_at),
  KEY idx_opportunities_work_mode (work_mode, status, verified_at),
  KEY idx_opportunities_discovered (discovered_at),
  CONSTRAINT fk_opportunities_source
    FOREIGN KEY (source_id) REFERENCES opportunity_sources (source_id)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
